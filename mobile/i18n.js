export function t(lang, key, vars = {}) {
  const table = text[lang] || text.zh;
  let line = table[key] ?? text.zh[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    line = line.replaceAll(`{${name}}`, String(value));
  }
  return line;
}

export function categoryLabel(lang, name) {
  const row = CATEGORIES.find((item) => item[0] === name);
  if (!row) return name;
  return lang === "en" ? row[1] : row[0];
}

export function categoryHint(lang, name) {
  const row = CATEGORIES.find((item) => item[0] === name);
  if (!row || lang === "en") return row ? row[1] : "";
  return row[2];
}
